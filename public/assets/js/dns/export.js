/* Multi-file export bundle: original files, manifest, validation scripts. */

import { downloadBlob, formatDateTime, sanitizeArchivePath, sha256Hex, shellQuote } from '../utils.js';
import { createZip } from './zip.js';
import { fileKindLabel, workspaceFingerprint, zoneDisplayName } from './workspace.js';
import { zoneDnssecInventory } from './dnssec.js';

const TOOL_NAME = 'BIND Workbench';
const TOOL_URL = 'https://github.com/RogerBergling/bind-gui';

function bundleSlug(name) {
  const slug = String(name || 'bind-workspace').toLowerCase().replace(/[^a-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '');
  return slug || 'bind-workspace';
}

function zoneValidationCommands(model) {
  const commands = [];
  for (const zone of model?.zones || []) {
    if (!zone.parsed || !zone.filePath) continue;
    commands.push({
      zone: zoneDisplayName(zone),
      file: zone.filePath,
      command: `named-checkzone ${shellQuote(zone.name)} ${shellQuote(zone.filePath)}`,
    });
  }
  return commands;
}

function verifierCommands(model) {
  const commands = [];
  const server = '1.1.1.1';
  for (const zone of model?.zones || []) {
    const name = zoneDisplayName(zone);
    if (!name || name === '.' || !zone.parsed) continue;
    commands.push(`dig @${server} ${shellQuote(zone.name)} NS +dnssec +multi`);
    commands.push(`dig @${server} ${shellQuote(zone.name)} SOA +dnssec +multi`);
    if ((zone.parsed.records || []).some((record) => record.type === 'MX')) {
      commands.push(`dig @${server} ${shellQuote(zone.name)} MX +dnssec +multi`);
    }
    commands.push(`dig @${server} ${shellQuote(zone.name)} DS +dnssec +multi`);
    commands.push(`dig @${server} ${shellQuote(zone.name)} DNSKEY +dnssec +multi`);
    commands.push(`dig +trace ${shellQuote(zone.name)} NS +dnssec`);
  }
  return Array.from(new Set(commands));
}

export async function buildExportFiles(workspace, model, options = {}) {
  const generatedAt = new Date().toISOString();
  const includeWorkspaceJson = options.includeWorkspaceJson !== false;
  const includeValidation = options.includeValidation !== false;
  const fileEntries = (workspace?.files || []).map((file) => ({
    path: sanitizeArchivePath(file.path) || file.name,
    content: file.content,
    kind: fileKindLabel(file.kind),
  }));
  const files = fileEntries.map((entry) => ({ path: entry.path, content: entry.content }));
  const hashedFiles = [];
  for (const entry of fileEntries) {
    const sha256 = await sha256Hex(entry.content);
    hashedFiles.push({
      path: entry.path,
      size: new TextEncoder().encode(entry.content).length,
      sha256,
      kind: entry.kind,
    });
  }
  const zones = (model?.zones || []).map((zone) => {
    const inventory = zoneDnssecInventory(zone?.parsed);
    return {
      name: zone.name,
      class: zone.class,
      type: zone.type || 'file',
      view: zone.view || null,
      file: zone.filePath || zone.fileOption || null,
      records: zone.parsed?.records?.length || 0,
      serial: zone.parsed?.soa?.data?.serial ?? null,
      dnssec: {
        signed: inventory.signed,
        keys: inventory.keys.length,
        ds: inventory.ds.length,
        denial: inventory.denial,
        managedSigning: Boolean(zone.options?.get('dnssec-policy')?.[0] || String(zone.options?.get('inline-signing')?.[0]?.args?.[0] || '').toLowerCase() === 'yes'),
      },
    };
  });
  const manifest = {
    tool: TOOL_NAME,
    toolUrl: TOOL_URL,
    generatedAt,
    workspace: {
      name: workspace?.name || 'BIND workspace',
      entry: workspace?.entry || null,
      files: fileEntries.length,
      zones: zones.length,
      fingerprint: workspace ? workspaceFingerprint(workspace) : null,
    },
    summary: model?.summary || null,
    analysis: options.analysisSummary || null,
    files: hashedFiles,
    zones,
    validation: {
      commands: zoneValidationCommands(model).map((item) => item.command),
      note: 'Run named-checkconf and named-checkzone against the exact BIND version and file paths used in production.',
    },
    limits: [
      'This bundle was produced by a browser tool; it is not a substitute for named-checkconf or named-checkzone.',
      'Absolute paths, file ownership, permissions, SELinux labels, AppArmor profiles and systemd sandboxing are outside this bundle.',
      'Review the diff before copying anything into a production configuration directory.',
    ],
  };
  files.push({
    path: 'BIND-WORKBENCH-MANIFEST.json',
    content: `${JSON.stringify(manifest, null, 2)}\n`,
  });

  if (includeValidation) {
    const checks = zoneValidationCommands(model);
    const verify = verifierCommands(model);
    const lines = [
      '#!/usr/bin/env sh',
      '# Generated by BIND Workbench. Review this script before running it.',
      '# It performs static checks only. It does not reload BIND or change live DNS.',
      'set -eu',
      'cd "$(dirname "$0")"',
      '',
      'if ! command -v named-checkconf >/dev/null 2>&1; then',
      '  echo "named-checkconf was not found. Install the BIND utilities and retry." >&2',
      '  exit 1',
      'fi',
      '',
      'echo "== named-checkconf =="',
      model?.entryFile
        ? `named-checkconf -z ${shellQuote(model.entryFile)}`
        : 'echo "No named.conf entry point was detected; skipping named-checkconf."',
      '',
    ];
    if (checks.length) {
      lines.push('echo "== named-checkzone =="');
      for (const item of checks) {
        lines.push(`echo ${shellQuote(`-- ${item.zone} (${item.file})`)}`);
        lines.push(item.command);
      }
      lines.push('');
    }
    lines.push('echo "Static checks passed. This does not prove live DNS correctness."');
    lines.push('echo "Next: inspect the diff, copy files into place, run rndc reload, then verify with dig."');
    lines.push('');
    files.push({ path: 'validate.sh', content: lines.join('\n') });

    const validationMd = [
      `# Validation plan for ${workspace?.name || 'this BIND workspace'}`,
      '',
      `Generated ${formatDateTime(generatedAt)}.`,
      '',
      '## 1. Review the bundle',
      '',
      '- Read `BIND-WORKBENCH-MANIFEST.json` and compare the file list and SHA-256 hashes with what you expect.',
      '- Open `validate.sh`; it uses only `named-checkconf` and `named-checkzone`.',
      '- Review every changed file with your normal change-control process.',
      '',
      '## 2. Run the static checks',
      '',
      '```sh',
      'chmod +x validate.sh',
      './validate.sh',
      '```',
      '',
      '`named-checkconf -z` parses the configuration and loads zone files. `named-checkzone` checks one zone in detail. Both must use the same BIND version and the same absolute paths as production.',
      '',
      '## 3. Check what the static tools cannot see',
      '',
      '- Absolute include and zone paths must exist on the target host.',
      '- File ownership, permissions, AppArmor/SELinux labels and systemd sandboxing are outside the bundle.',
      '- TSIG secrets, DNSSEC private keys and trust anchors need protected permissions.',
      '- `named-checkconf` does not prove that the live DNS data, delegations, firewall rules or DNSSEC chain are correct.',
      '',
      '## 4. Deploy deliberately',
      '',
      '```sh',
      'sudo named-checkconf -z /etc/bind/named.conf',
      'sudo rndc reload',
      'sudo rndc status',
      '```',
      '',
      'Then verify from outside the server with the commands in `VERIFY.md` and the Live DNS page of BIND Workbench.',
      '',
      '## Included checks',
      '',
      '```text',
      ...(checks.length ? checks.map((item) => item.command) : ['(no zone files were referenced)']),
      '```',
      '',
    ];
    files.push({ path: 'VALIDATE.md', content: validationMd.join('\n') });

    const verifyMd = [
      `# Live verification for ${workspace?.name || 'this BIND workspace'}`,
      '',
      'These commands use public recursive resolvers. They are a propagation check, not an authoritative test.',
      '',
      '```sh',
      ...verify,
      '```',
      '',
      'Use `dig @<zone-nameserver> <name> <type> +norecurse +dnssec` for authoritative answers. Use `delv` or `dig +dnssec` and inspect the `ad` flag for validation status.',
      '',
      'Remember: cached answers, GeoDNS, views and round-robin pools can legitimately differ between resolvers.',
      '',
    ];
    files.push({ path: 'VERIFY.md', content: verifyMd.join('\n') });
  }

  if (includeWorkspaceJson) {
    files.push({
      path: 'bind-workbench-workspace.json',
      content: `${JSON.stringify({
        format: 'bind-workbench-workspace',
        version: 1,
        exportedAt: generatedAt,
        warning: 'This file contains the complete workspace, including any TSIG secrets or private-key material present in the source files. Store it accordingly.',
        workspace,
      }, null, 2)}\n`,
    });
  }

  const unique = new Map();
  for (const file of files) {
    const path = sanitizeArchivePath(file.path);
    if (!path) continue;
    if (unique.has(path)) {
      unique.set(path, { ...file, path: `${path}.duplicate` });
    } else {
      unique.set(path, { ...file, path });
    }
  }
  return {
    files: Array.from(unique.values()),
    manifest,
    filename: `${bundleSlug(workspace?.name)}-bind-bundle.zip`,
  };
}

export async function downloadWorkspaceZip(workspace, model, options = {}) {
  const bundle = await buildExportFiles(workspace, model, options);
  const zip = await createZip(bundle.files, { compress: true });
  downloadBlob(bundle.filename, new Blob([zip], { type: 'application/zip' }));
  return bundle;
}

export function buildWorkspaceJson(workspace) {
  return `${JSON.stringify({
    format: 'bind-workbench-workspace',
    version: 1,
    exportedAt: new Date().toISOString(),
    warning: 'This file contains the complete workspace, including any TSIG secrets or private-key material present in the source files. Store it accordingly.',
    workspace,
  }, null, 2)}\n`;
}

export function downloadWorkspaceJson(workspace) {
  const content = buildWorkspaceJson(workspace);
  downloadBlob(`${bundleSlug(workspace?.name)}-workspace.json`, new Blob([content], { type: 'application/json' }));
}

export function downloadWorkspaceFile(file) {
  downloadBlob(file.name || file.path, new Blob([file.content], { type: 'text/plain;charset=utf-8' }));
}

export { bundleSlug };
