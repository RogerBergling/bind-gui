for (const doc of DIRECTIVE_DOCS) {
  const keys = String(doc.keyword || doc.id).split('/').map((part) => part.trim().toLowerCase());
  for (const key of keys) {
    if (!DIRECTIVE_BY_KEYWORD.has(key)) DIRECTIVE_BY_KEYWORD.set(key, doc);
  }
  if (!DIRECTIVE_BY_KEYWORD.has(doc.id.toLowerCase())) DIRECTIVE_BY_KEYWORD.set(doc.id.toLowerCase(), doc);
}

export function directiveDoc(keyword) {
  const key = String(keyword || '').split(/\s+/)[0].toLowerCase();
  return DIRECTIVE_BY_KEYWORD.get(key) || DIRECTIVE_BY_KEYWORD.get(String(keyword || '').toLowerCase()) || null;
}

